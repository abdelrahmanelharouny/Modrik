#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────
// Modrik (مدرك) — Postgres schema sync
//
// SQLite is the canonical Prisma schema. PostgreSQL is generated
// deterministically by changing only the datasource provider.
// Keep the renderer pure so CI can compare both schemas without
// mutating files as a side effect.
// ─────────────────────────────────────────────────────────────

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "prisma", "schema.prisma");
const dst = join(root, "prisma", "schema.postgres.prisma");

const HEADER = `// ─────────────────────────────────────────────────────────────
 // AUTO-GENERATED — DO NOT EDIT BY HAND
 // Generated by scripts/sync-postgres-schema.mjs from
 // prisma/schema.prisma (the single source of truth).
 // Difference: datasource provider "postgresql" only.
 // Regenerate with: npm run db:sync:pg
 // ─────────────────────────────────────────────────────────────

`.replace(/^ /gm, "");

export function renderPostgresSchema(sqliteSchema) {
  if (typeof sqliteSchema !== "string" || sqliteSchema.length === 0) {
    throw new TypeError("SQLite schema must be a non-empty string");
  }

  const datasource = /datasource\s+db\s*\\{[^}]*\\}/.exec(sqliteSchema);
  if (!datasource) {
    throw new Error("could not locate the datasource block in schema.prisma");
  }

  const postgresBlock = datasource[0].replace(
    /provider\s*=\s*"sqlite"/,
    'provider = "postgresql"'
  );
  if (postgresBlock === datasource[0]) {
    throw new Error('datasource provider must be "sqlite" before PostgreSQL generation');
  }

  return HEADER + sqliteSchema.replace(datasource[0], postgresBlock);
}

function main() {
  const sqliteSchema = readFileSync(src, "utf8");
  const postgresSchema = renderPostgresSchema(sqliteSchema);
  writeFileSync(dst, postgresSchema, "utf8");
  console.log("✓ generated prisma/schema.postgres.prisma (provider: postgresql)");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
